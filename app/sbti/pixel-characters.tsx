// ─── 导出渲染组件 ──────────────────────────────────────
export function PixelCharacter({
  code,
  color,
  size = 6,
  animate = true,
}: {
  code: string
  color: string
  size?: number
  animate?: boolean
}) {
  const data = PIXEL_CHARS[code]
  if (!data) return null

  return (
    <div style={{
      display: 'inline-block',
      animation: animate ? 'pixel-bounce 2s ease-in-out infinite' : 'none',
      imageRendering: 'pixelated',
    }}>
      <PixelCanvas grid={data.grid} color={color} accent={data.accent} size={size} />
    </div>
  )
}
