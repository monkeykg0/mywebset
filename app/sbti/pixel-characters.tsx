// 工具：把点阵字符串转为 box-shadow 字符串
// 点阵用 16x20 格子，'1'=填色, '0'=透明
function toBoxShadow(grid: string[], color: string, accent: string, px: number) {
  const shadows: string[] = []
  grid.forEach((row, y) => {
    row.split('').forEach((cell, x) => {
      if (cell === '1') shadows.push(`${x * px}px ${y * px}px 0 ${color}`)
      if (cell === '2') shadows.push(`${x * px}px ${y * px}px 0 ${accent}`)
      if (cell === '3') shadows.push(`${x * px}px ${y * px}px 0 #fff`)
      if (cell === '4') shadows.push(`${x * px}px ${y * px}px 0 #1a1a2e`)
    })
  })
  return shadows.join(',')
}

// ─── 通用像素人物渲染器 ────────────────────────────────
function PixelCanvas({ grid, color, accent, size = 6 }: {
  grid: string[]
  color: string
  accent: string
  size?: number
}) {
  const cols = grid[0]?.length ?? 12
  const rows = grid.length
  return (
    <div style={{
      position: 'relative',
      width: cols * size,
      height: rows * size,
      imageRendering: 'pixelated',
      flexShrink: 0,
    }}>
      <div style={{
        position: 'absolute',
        top: 0, left: 0,
        width: size,
        height: size,
        boxShadow: toBoxShadow(grid, color, accent, size),
        imageRendering: 'pixelated',
      }} />
    </div>
  )
}

